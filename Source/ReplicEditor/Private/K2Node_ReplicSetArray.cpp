{
	const FText ResolvedName = GetResolvedDisplayName();
	return ResolvedName.IsEmpty()
		? LOCTEXT("ReplicSetArrayTitle", "Replic Set Array")
		: FText::Format(LOCTEXT("ReplicSetArraySelectedTitle", "Replic Set {0}"), ResolvedName);
}

