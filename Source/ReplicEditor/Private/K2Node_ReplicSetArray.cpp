void UK2Node_ReplicSetArray::GetMenuActions(FBlueprintActionDatabaseRegistrar& ActionRegistrar) const
{
	UClass* ActionKey = GetClass();
	if (!ActionRegistrar.IsOpenForRegistration(ActionKey))
	{
		return;
	}

	UBlueprintNodeSpawner* Spawner = UBlueprintNodeSpawner::Create(GetClass());
	check(Spawner);
	ActionRegistrar.AddBlueprintAction(ActionKey, Spawner);
}

void UK2Node_ReplicSetArray::EarlyValidation(FCompilerResultsLog& MessageLog) const
{
	Super::EarlyValidation(MessageLog);

	const UEdGraphPin* PropertyPin = GetPropertyNamePin();
	const FName SelectedPropertyName(*PropertyPin->GetDefaultAsString());
	if (SelectedPropertyName.IsNone())
	{
		MessageLog.Error(TEXT("Replic: No array property is selected for @@"), this);
		return;
	}

	const FArrayProperty* SelectedProperty = ResolveSelectedArrayProperty();
	if (!SelectedProperty)
	{
		UClass* TargetClass = nullptr;
		if (!ReplicPinOptionResolver::ResolveTargetClass(PropertyPin, TargetClass))
		{
			MessageLog.Warning(TEXT("Replic: TargetObject could not be resolved to a concrete class for @@"), this);
			return;
		}

		MessageLog.Error(
			*FString::Printf(TEXT("Replic: '%s' is not a Replic-marked array property on target class '%s' for @@"), *SelectedPropertyName.ToString(), *TargetClass->GetName()),
			this);
		return;
	}

	if (!ReplicK2NodeUtils::ArePinAndPropertyCompatible(GetValuePin(), SelectedProperty))
	{
		MessageLog.Error(TEXT("Replic: Value pin does not match the selected array property for @@"), this);
	}

	if (const UBlueprint* Blueprint = GetBlueprint())
	{
		if (UsesSelfAsContext(GetContextObjectPin()) && !ReplicK2NodeUtils::HasReplicTransportComponent(Blueprint))
		{
			MessageLog.Warning(TEXT("Replic: This Blueprint does not currently contain a ReplicTransportComponent. Client-side requests from Self may fail for @@"), this);
		}
	}
}

void UK2Node_ReplicSetArray::PostReconstructNode()
{
	RefreshValuePinType();
	Super::PostReconstructNode();
}

void UK2Node_ReplicSetArray::PostLoad()
{
	Super::PostLoad();
	RefreshValuePinType();
}

void UK2Node_ReplicSetArray::RefreshValuePinType()
{
	if (bIsRefreshingPins)
	{
		return;
	}

	TGuardValue<bool> RefreshGuard(bIsRefreshingPins, true);

	UEdGraphPin* ValuePin = FindPin(ValuePinName);
	if (!ValuePin)
	{
		return;
	}

	FEdGraphPinType NewPinType = MakeNeutralArrayPinType();
	if (const FArrayProperty* ArrayProperty = ResolveSelectedArrayProperty())
	{
		ReplicK2NodeUtils::ConvertPropertyToPinType(ArrayProperty, NewPinType);
	}

	const UEdGraphSchema_K2* K2Schema = GetDefault<UEdGraphSchema_K2>();
	if (!(ValuePin->PinType == NewPinType))
	{
		if (K2Schema && !K2Schema->ArePinTypesCompatible(ValuePin->PinType, NewPinType))
		{
			ValuePin->BreakAllPinLinks();
		}

		ValuePin->PinType = NewPinType;
	}

	if (ValuePin->LinkedTo.Num() == 0 && NewPinType.PinCategory == UEdGraphSchema_K2::PC_Wildcard)
	{
		ValuePin->DefaultValue.Reset();
		ValuePin->AutogeneratedDefaultValue.Reset();
		ValuePin->DefaultObject = nullptr;
		ValuePin->DefaultTextValue = FText::GetEmpty();
	}

	ReplicK2NodeUtils::SetPinToolTip(ValuePin, TEXT("New array value written to the selected Replic property.\n\nThis pin must match the selected array property's type."));
	ReplicK2NodeUtils::SetPinToolTip(GetPropertyNamePin(), TEXT("Choose the Replic-marked array property to write.\n\nThe list is filtered by the connected TargetObject when the editor can resolve it."));
	ReplicK2NodeUtils::SetPinToolTip(GetTargetObjectPin(), TEXT("Object that owns the Replic-marked array property.\n\nLeave this unconnected only when the property is on Self or in the current Blueprint."));
	ReplicK2NodeUtils::SetPinToolTip(GetContextObjectPin(), TEXT("Object used to identify who is making the network request.\n\nUsually this should be Self on the calling Character, Pawn, PlayerController, Actor, or Component that has access to a ReplicTransportComponent."));
}

const FArrayProperty* UK2Node_ReplicSetArray::ResolveSelectedArrayProperty() const
{
	const UEdGraphPin* PropertyPin = FindPin(PropertyNamePinName);
	if (!PropertyPin)
	{
		return nullptr;
	}

	const FName SelectedPropertyName(*PropertyPin->GetDefaultAsString());
	const FProperty* Property = nullptr;
	if (ReplicPinOptionResolver::ResolveMarkedProperty(PropertyPin, SelectedPropertyName, Property))
	{
		return CastField<FArrayProperty>(Property);
	}

	return nullptr;
}

FText UK2Node_ReplicSetArray::GetResolvedDisplayName() const
{
	if (const UEdGraphPin* PropertyPin = FindPin(PropertyNamePinName))
	{
		const FName SelectedPropertyName(*PropertyPin->GetDefaultAsString());
		if (!SelectedPropertyName.IsNone())
		{
			return FText::FromName(SelectedPropertyName);
		}
	}

	return FText::GetEmpty();
}

