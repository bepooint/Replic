void UK2Node_ReplicSetEnum::GetMenuActions(FBlueprintActionDatabaseRegistrar& ActionRegistrar) const
{
	UClass* ActionKey = GetClass();
	if (!ActionRegistrar.IsOpenForRegistration(ActionKey))
	{
		return;
	}

	UBlueprintNodeSpawner* Spawner = UBlueprintNodeSpawner::Create(GetClass());
	check(Spawner);
	ActionRegistrar.AddBlueprintAction(ActionKey, Spawner);
}

void UK2Node_ReplicSetEnum::EarlyValidation(FCompilerResultsLog& MessageLog) const
{
	Super::EarlyValidation(MessageLog);

	const UEdGraphPin* PropertyPin = GetPropertyNamePin();
	const FName SelectedPropertyName(*PropertyPin->GetDefaultAsString());
	if (SelectedPropertyName.IsNone())
	{
		MessageLog.Error(TEXT("Replic: No enum property is selected for @@"), this);
		return;
	}

	const FProperty* SelectedProperty = ResolveSelectedEnumProperty();
	if (!SelectedProperty)
	{
		UClass* TargetClass = nullptr;
		if (!ReplicPinOptionResolver::ResolveTargetClass(PropertyPin, TargetClass))
		{
			MessageLog.Warning(TEXT("Replic: TargetObject could not be resolved to a concrete class for @@"), this);
			return;
		}

		MessageLog.Error(
			*FString::Printf(TEXT("Replic: '%s' is not a Replic-marked enum property on target class '%s' for @@"), *SelectedPropertyName.ToString(), *TargetClass->GetName()),
			this);
		return;
	}

	if (!ReplicK2NodeUtils::ArePinAndPropertyCompatible(GetValuePin(), SelectedProperty))
	{
		MessageLog.Error(TEXT("Replic: Value pin does not match the selected enum property for @@"), this);
	}

	if (const UBlueprint* Blueprint = GetBlueprint())
	{
		if (UsesSelfAsContext(GetContextObjectPin()) && !ReplicK2NodeUtils::HasReplicTransportComponent(Blueprint))
		{
			MessageLog.Warning(TEXT("Replic: This Blueprint does not currently contain a ReplicTransportComponent. Client-side requests from Self may fail for @@"), this);
		}
	}
}

void UK2Node_ReplicSetEnum::PostReconstructNode()
{
	RefreshValuePinType();
	Super::PostReconstructNode();
}

void UK2Node_ReplicSetEnum::PostLoad()
{
	Super::PostLoad();
	RefreshValuePinType();
}

void UK2Node_ReplicSetEnum::RefreshValuePinType()
{
	if (bIsRefreshingPins)
	{
		return;
	}

	TGuardValue<bool> RefreshGuard(bIsRefreshingPins, true);

	UEdGraphPin* ValuePin = FindPin(ValuePinName);
	UEdGraphPin* PropertyPin = FindPin(PropertyNamePinName);
	if (!ValuePin)
	{
		return;
	}

	FEdGraphPinType NewPinType;
	NewPinType.PinCategory = UEdGraphSchema_K2::PC_Byte;
	if (const UEnum* Enum = ResolveSelectedEnum())
	{
		NewPinType.PinSubCategoryObject = const_cast<UEnum*>(Enum);
		ValuePin->PinType = NewPinType;

		const FName ExistingPinValue = ResolveEnumValueFromPin(ValuePin, Enum);
		if (!bHasPersistedEnumSelection && !ExistingPinValue.IsNone())
		{
			PersistedEnumValue = ExistingPinValue;
			bHasPersistedEnumSelection = true;
		}

		if (ValuePin->LinkedTo.Num() == 0)
		{
			FName EffectiveValue = NAME_None;
			if (!ExistingPinValue.IsNone())
			{
				EffectiveValue = ExistingPinValue;
			}
			else if (bHasPersistedEnumSelection && EnumContainsValueName(Enum, PersistedEnumValue))
			{
				EffectiveValue = PersistedEnumValue;
			}
			else
			{
				EffectiveValue = GetFirstUsableEnumValueName(Enum);
			}

			if (!EffectiveValue.IsNone())
			{
				const FString SerializedValue = EffectiveValue.ToString();
				ValuePin->DefaultValue = SerializedValue;
				ValuePin->AutogeneratedDefaultValue = SerializedValue;
				PersistedEnumValue = EffectiveValue;
				bHasPersistedEnumSelection = true;
			}
		}
	}
	else
	{
		ValuePin->PinType = NewPinType;
		if (ValuePin->LinkedTo.Num() == 0)
		{
			const bool bHasPropertySelection = PropertyPin && !PropertyPin->GetDefaultAsString().IsEmpty();
			if (!bHasPropertySelection)
			{
				bHasPersistedEnumSelection = false;
				PersistedEnumValue = NAME_None;
				ValuePin->DefaultValue.Reset();
				ValuePin->AutogeneratedDefaultValue.Reset();
				ValuePin->DefaultTextValue = FText::GetEmpty();
			}
		}
	}

	ReplicK2NodeUtils::SetPinToolTip(ValuePin, TEXT("New enum value that should be written and replicated."));
	ReplicK2NodeUtils::SetPinToolTip(GetPropertyNamePin(), TEXT("Choose the Replic-marked enum property to write.\n\nThe list is filtered by the connected TargetObject when the editor can resolve it."));
	ReplicK2NodeUtils::SetPinToolTip(GetTargetObjectPin(), TEXT("Object that owns the Replic-marked enum property.\n\nLeave this unconnected only when the property is on Self or in the current Blueprint."));
	ReplicK2NodeUtils::SetPinToolTip(GetContextObjectPin(), TEXT("Object used to identify who is making the network request.\n\nUsually this should be Self on the calling Character, Pawn, PlayerController, Actor, or Component that has access to a ReplicTransportComponent."));
}

const FProperty* UK2Node_ReplicSetEnum::ResolveSelectedEnumProperty() const
{
	const UEdGraphPin* PropertyPin = FindPin(PropertyNamePinName);
	if (!PropertyPin)
	{
		return nullptr;
	}

	const FName SelectedPropertyName(*PropertyPin->GetDefaultAsString());
	const FProperty* Property = nullptr;
	if (ReplicPinOptionResolver::ResolveMarkedProperty(PropertyPin, SelectedPropertyName, Property) && IsEnumLikeProperty(Property))
	{
		return Property;
	}

	return nullptr;
}

UEnum* UK2Node_ReplicSetEnum::ResolveSelectedEnum() const
{
	const UEdGraphPin* PropertyPin = FindPin(PropertyNamePinName);
	if (!PropertyPin)
	{
		return nullptr;
	}

	const FName SelectedPropertyName(*PropertyPin->GetDefaultAsString());
	const FProperty* Property = ResolveSelectedEnumProperty();
	if (Property)
	{
		return ResolveEnumFromProperty(Property);
	}

	return nullptr;
}

FText UK2Node_ReplicSetEnum::GetResolvedDisplayName() const
{
	if (const UEdGraphPin* PropertyPin = FindPin(PropertyNamePinName))
	{
		const FName SelectedPropertyName(*PropertyPin->GetDefaultAsString());
		if (!SelectedPropertyName.IsNone())
		{
			return FText::FromName(SelectedPropertyName);
		}
	}

	return FText::GetEmpty();
}

