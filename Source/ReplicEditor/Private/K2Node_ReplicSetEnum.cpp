void UK2Node_ReplicSetEnum::HandleReplicSelectionChanged(FName ChangedPinName)
{
	if (ChangedPinName != PropertyNamePinName || bIsRefreshingPins)
	{
		return;
	}

	ReconstructNode();
	if (UEdGraph* Graph = GetGraph())
	{
		Graph->NotifyNodeChanged(this);
	}
}

void UK2Node_ReplicSetEnum::HandleEnumValueSelectionChanged(FName NewEnumValue)
{
	Modify();
	bHasPersistedEnumSelection = true;
	PersistedEnumValue = NewEnumValue;

	if (UBlueprint* Blueprint = GetBlueprint())
	{
		FBlueprintEditorUtils::MarkBlueprintAsModified(Blueprint);
	}

	if (UEdGraph* Graph = GetGraph())
	{
		Graph->NotifyNodeChanged(this);
	}
}

void UK2Node_ReplicSetEnum::AllocateDefaultPins()
{
	CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Exec, ExecPinName);
	CreatePin(EGPD_Output, UEdGraphSchema_K2::PC_Exec, ThenPinName);

	UEdGraphPin* ContextPin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Object, UObject::StaticClass(), ContextObjectPinName);
	ContextPin->bAdvancedView = true;
	CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Object, UObject::StaticClass(), TargetObjectPinName);
	CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Name, PropertyNamePinName);
	CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Byte, ValuePinName);
	CreatePin(EGPD_Output, UEdGraphSchema_K2::PC_Boolean, SuccessPinName);

	RefreshValuePinType();
	Super::AllocateDefaultPins();
}

void UK2Node_ReplicSetEnum::ExpandNode(FKismetCompilerContext& CompilerContext, UEdGraph* SourceGraph)
{
	Super::ExpandNode(CompilerContext, SourceGraph);

	const FProperty* SelectedProperty = ResolveSelectedEnumProperty();
	if (!SelectedProperty)
	{
		CompilerContext.MessageLog.Error(*LOCTEXT("MissingReplicEnumProperty", "Replic: No valid Replic enum property is selected for @@").ToString(), this);
		BreakAllNodeLinks();
		return;
	}

	UK2Node_CallFunction* CallNode = CompilerContext.SpawnIntermediateNode<UK2Node_CallFunction>(this, SourceGraph);
	CallNode->SetFromFunction(UReplicLibrary::StaticClass()->FindFunctionByName(GET_FUNCTION_NAME_CHECKED(UReplicLibrary, SetMarkedEnum)));
	CallNode->AllocateDefaultPins();

	CompilerContext.MovePinLinksToIntermediate(*GetExecPin(), *CallNode->GetExecPin());
	CompilerContext.MovePinLinksToIntermediate(*GetThenPin(), *CallNode->GetThenPin());
	MovePinLinksOrCopyDefaults(CompilerContext, GetContextObjectPin(), CallNode->FindPinChecked(ContextObjectPinName), true);
	MovePinLinksOrCopyDefaults(CompilerContext, GetTargetObjectPin(), CallNode->FindPinChecked(TargetObjectPinName));
	MovePinLinksOrCopyDefaults(CompilerContext, GetPropertyNamePin(), CallNode->FindPinChecked(PropertyNamePinName));

	UEdGraphPin* IntermediateValuePin = CallNode->FindPinChecked(ValuePinName);
	IntermediateValuePin->PinType = GetValuePin()->PinType;
	MovePinLinksOrCopyDefaults(CompilerContext, GetValuePin(), IntermediateValuePin);

	CompilerContext.MovePinLinksToIntermediate(*GetSuccessPin(), *CallNode->GetReturnValuePin());
	BreakAllNodeLinks();
}

void UK2Node_ReplicSetEnum::PinDefaultValueChanged(UEdGraphPin* Pin)
{
	Super::PinDefaultValueChanged(Pin);
	if (Pin && Pin->PinName == PropertyNamePinName)
	{
		ReconstructNode();
		if (UEdGraph* Graph = GetGraph())
		{
			Graph->NotifyNodeChanged(this);
		}
	}
}

void UK2Node_ReplicSetEnum::PinConnectionListChanged(UEdGraphPin* Pin)
{
	Super::PinConnectionListChanged(Pin);
	if (Pin && Pin->PinName == TargetObjectPinName)
	{
		ReconstructNode();
		if (UEdGraph* Graph = GetGraph())
		{
			Graph->NotifyNodeChanged(this);
		}
	}
}

FText UK2Node_ReplicSetEnum::GetNodeTitle(ENodeTitleType::Type TitleType) const
{
	const FText ResolvedName = GetResolvedDisplayName();
	return ResolvedName.IsEmpty()
		? LOCTEXT("ReplicSetEnumTitle", "Replic Set Enum")
		: FText::Format(LOCTEXT("ReplicSetEnumSelectedTitle", "Replic Set {0}"), ResolvedName);
}

